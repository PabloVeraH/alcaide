"""Download independent public prompt-injection datasets as `alcaide bench`
corpora, for measuring the rule set against data it was not written from.

    python benchmarks/fetch_public.py
    alcaide bench --corpus benchmarks/public/deepset-test.yaml

Output goes to benchmarks/public/ (git-ignored): the datasets keep their own
licenses and stay out of the repository, which also keeps them out of reach
when writing rules.

Protocol: the *test* splits are the held-out measurement and are never read
to write or tune a rule. The *train* splits may be studied for rule work.

Python standard library only.
"""

import json
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

# (name, Hugging Face dataset, revision measured in BENCHMARKS.md, text field, label function)
DATASETS = [
    (
        "deepset",
        "deepset/prompt-injections",
        "4f61ecb038e9c3fb77e21034b22511b523772cdd",
        "text",
        lambda row: "malicious" if str(row["label"]) == "1" else "benign",
    ),
    (
        "gandalf",
        "Lakera/gandalf_ignore_instructions",
        "04737b65e90a6794ec227012e4a255a7def6344b",
        "text",
        lambda row: "malicious",  # every row is an injection attempt
    ),
    (
        "jailbreak-classification",
        "jackhhao/jailbreak-classification",
        "2f2ceeb39658696fd3f462403562b6eea5306287",
        "prompt",
        lambda row: "malicious" if row["type"] == "jailbreak" else "benign",
    ),
]

SPLITS = ["train", "test"]
OUT = Path(__file__).parent / "public"
API = "https://datasets-server.huggingface.co/rows?dataset={}&config=default&split={}&offset={}&length=100"


def yaml_string(text):
    """A YAML double-quoted scalar for `text`. JSON's escaping is valid YAML,
    except that YAML also forbids raw C1 controls and noncharacters."""
    quoted = json.dumps(text, ensure_ascii=False)
    return "".join(
        f"\\u{ord(c):04x}" if 0x7F <= ord(c) <= 0x9F and c != "\x85" or c in "￾￿" else c
        for c in quoted
    )


def get_json(url, attempts=6):
    for attempt in range(attempts):
        try:
            with urllib.request.urlopen(url, timeout=60) as response:
                return json.load(response)
        except urllib.error.HTTPError as error:
            # The rows API rate-limits bursts of paginated requests.
            if error.code != 429 or attempt == attempts - 1:
                raise
            time.sleep(2**attempt * 5)


def rows(dataset, split):
    offset = 0
    while True:
        page = get_json(API.format(dataset, split, offset))
        for item in page["rows"]:
            yield item["row_idx"], item["row"]
        offset += len(page["rows"])
        if not page["rows"] or offset >= page["num_rows_total"]:
            return


def main():
    OUT.mkdir(exist_ok=True)
    for name, dataset, revision, text_field, label_of in DATASETS:
        current = get_json(f"https://huggingface.co/api/datasets/{dataset}")["sha"]
        if current != revision:
            # The rows API serves the latest revision only.
            print(
                f"warning: {dataset} is at {current}, BENCHMARKS.md measured {revision}; "
                "results may differ",
                file=sys.stderr,
            )
        for split in SPLITS:
            path = OUT / f"{name}-{split}.yaml"
            count = 0
            with path.open("w", encoding="utf-8", newline="\n") as out:
                out.write(f"# {dataset} @ {current}, split {split}. Generated by fetch_public.py.\n")
                for idx, row in rows(dataset, split):
                    text = row[text_field]
                    if not text or not text.strip():
                        continue
                    out.write(f"- prompt: {yaml_string(text)}\n")
                    out.write(f"  label: {label_of(row)}\n")
                    out.write(f'  source: "{dataset} {split} row {idx}"\n')
                    count += 1
            print(f"{path}: {count} prompts")


if __name__ == "__main__":
    main()
